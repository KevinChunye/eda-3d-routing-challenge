"""Falsification test for "batch matching": can one integer program over a pool of candidate
trees per net beat a given solution?

Columns per net: the given solution's tree (so the program can never do worse) plus trees
generated by one of two pricing modes, each a shortest-path tree with other nets' pins
blocked and a toll on every grid point:
  --mode price  surge prices: tolls rise where independently routed nets overlap
                (subgradient steps), every net re-routed each round;
  --mode cg     column generation: tolls are the dual prices of the LP over the current
                pool; a tree enters if its reduced cost (delay + tolls - net value) < 0.
Master: min total delay s.t. one tree per net and each grid point used by at most one tree.
LP relaxation and integer optimum (HiGHS via scipy) are reported; the chosen routes are
written as a submission so the repo checker can verify them.

Result 2026-10-18 (hard case_05, 120 s single-thread incumbent 15,645): price mode 8,881
columns -> LP = MIP = 15,645; cg mode 40 rounds, 4,111 columns -> LP never moved. See
findings.md.

Usage (from repo root):
  python3 -I research/tools/pool_selection.py --tier hard --case case_05 \
      --solution <our .sol.json> --mode price --rounds 120 --mip-seconds 240 --out pool.sol.json
"""
import argparse
import json
import os
import sys
import time

import numpy as np
import pandas as pd
from scipy.optimize import LinearConstraint, linprog, milp
from scipy.sparse import coo_matrix, csr_matrix
from scipy.sparse.csgraph import dijkstra

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

ap = argparse.ArgumentParser()
ap.add_argument("--tier", required=True)
ap.add_argument("--case", required=True)
ap.add_argument("--solution", required=True, help="our own route file (never another entry's)")
ap.add_argument("--mode", choices=["price", "cg"], default="price")
ap.add_argument("--rounds", type=int, default=120)
ap.add_argument("--mip-seconds", type=float, default=240)
ap.add_argument("--out", required=True)
args = ap.parse_args()

suite = "benchmarks" if args.tier == "intro" else f"benchmarks_{args.tier}"
inst = json.load(open(os.path.join(REPO, suite, f"{args.case}.json")))
W, H, L = inst["grid"]["width"], inst["grid"]["height"], inst["grid"]["layers"]
ld, via = inst["delay"]["layer_delay"], inst["delay"]["via_delay"]
NV = W * H * L


def vid(x, y, z):
    return (z * H + y) * W + x


def xyz(v):
    return [v % W, (v // W) % H, v // (W * H)]


# grid graph in CSR order so only the edge weights change between pricing rounds
idx = np.arange(NV).reshape(L, H, W)
tails, heads, base = [], [], []
for z in range(L):
    for a, b in [(idx[z, :, :-1], idx[z, :, 1:]), (idx[z, :-1, :], idx[z, 1:, :])]:
        a, b = a.ravel(), b.ravel()
        tails += [a, b]
        heads += [b, a]
        base += [np.full(2 * a.size, ld[z])]
for z in range(L - 1):
    a, b = idx[z].ravel(), idx[z + 1].ravel()
    tails += [a, b]
    heads += [b, a]
    base += [np.full(2 * a.size, via)]
tails, heads = np.concatenate(tails), np.concatenate(heads)
base = np.concatenate(base).astype(float)
order = np.lexsort((heads, tails))
tails, heads, base = tails[order], heads[order], base[order]
indptr = np.searchsorted(tails, np.arange(NV + 1))
edge_w = dict(zip(zip(tails.tolist(), heads.tolist()), base.tolist()))

pins = {p["id"]: vid(p["x"], p["y"], p["z"]) for p in inst["pins"]}
nets = inst["nets"]
pin_owner = np.full(NV, -1)
for i, n in enumerate(nets):
    for p in [n["driver"]] + n["sinks"]:
        pin_owner[pins[p]] = i
head_owner = pin_owner[heads]
blocked = [np.flatnonzero((head_owner >= 0) & (head_owner != i)) for i in range(len(nets))]


def tree_delay(parent, sinks):
    total = 0.0
    for s in sinks:
        v = s
        while parent[v] != -1:
            total += edge_w[(parent[v], v)]
            v = parent[v]
    return total


def priced_tree(i, tolls):
    data = base + tolls[heads]
    data[blocked[i]] = 1e9
    g = csr_matrix((data, heads, indptr), shape=(NV, NV))
    drv = pins[nets[i]["driver"]]
    sinks = [pins[s] for s in nets[i]["sinks"]]
    _, pred = dijkstra(g, directed=True, indices=drv, return_predecessors=True)
    parent = {drv: -1}
    for s in sinks:
        path, v = [], s
        while v not in parent:
            path.append(v)
            v = int(pred[v])
            if v < 0:
                return None
        for u in reversed(path):
            parent[u] = v
            v = u
    return frozenset(parent), parent, tree_delay(parent, sinks)


# columns from the given solution
cols = []
net_index = {n["id"]: i for i, n in enumerate(nets)}
for r in json.load(open(args.solution))["routes"]:
    i = net_index[r["net"]]
    adj = {}
    for a, b in r["edges"]:
        u, v = vid(*a), vid(*b)
        for p, q in ((u, v), (v, u)):
            if p not in adj:
                adj[p] = []
            adj[p].append(q)
    drv = pins[nets[i]["driver"]]
    parent, stack = {drv: -1}, [drv]
    while stack:
        u = stack.pop()
        for q in adj.get(u, []):
            if q not in parent:
                parent[q] = u
                stack.append(q)
    sinks = [pins[s] for s in nets[i]["sinks"]]
    cols.append(dict(net=i, verts=frozenset(parent), parent=parent,
                     delay=tree_delay(parent, sinks), source="given"))
given_total = sum(c["delay"] for c in cols)
print(f"given solution {given_total:.0f}  ({len(nets)} nets, grid {W}x{H}x{L})", flush=True)
seen = {(c["net"], c["verts"]) for c in cols}


def matrices():
    rows, cid = [], []
    for j, c in enumerate(cols):
        rows += list(c["verts"])
        cid += [j] * len(c["verts"])
    A = coo_matrix((np.ones(len(rows)), (rows, cid)), shape=(NV, len(cols))).tocsr()
    netv = np.array([c["net"] for c in cols])
    A_one = coo_matrix((np.ones(len(cols)), (netv, np.arange(len(cols)))),
                       shape=(len(nets), len(cols))).tocsr()
    return A, A_one, np.array([c["delay"] for c in cols])


t0 = time.time()
lam = np.zeros(NV)
for rnd in range(args.rounds):
    added = 0
    if args.mode == "price":
        usage = np.zeros(NV)
        for i, n in enumerate(nets):
            for w in ([1.0 / len(n["sinks"])] if rnd % 3 else [1.0 / len(n["sinks"]), 1.0]):
                tr = priced_tree(i, w * lam)
                if tr is None:
                    continue
                verts, parent, delay = tr
                if w == 1.0 / len(n["sinks"]):
                    usage[list(verts)] += 1
                if (i, verts) not in seen:
                    seen.add((i, verts))
                    cols.append(dict(net=i, verts=verts, parent=parent, delay=delay, source="price"))
                    added += 1
        lam = np.maximum(0.0, lam + 0.995 ** rnd * (usage - 1.0))
        if rnd % 10 == 0:
            print(f"  round {rnd}: overused points {(usage > 1).sum()}, columns {len(cols)}, "
                  f"{time.time() - t0:.0f}s", flush=True)
    else:
        A, A_one, c = matrices()
        lp = linprog(c, A_ub=A, b_ub=np.ones(NV), A_eq=A_one, b_eq=np.ones(len(nets)),
                     bounds=(0, 1), method="highs")
        pi, mu = -lp.ineqlin.marginals, lp.eqlin.marginals
        best_rc = 0.0
        for i, n in enumerate(nets):
            for w in sorted({1.0 / len(n["sinks"]), 1.0}):
                tr = priced_tree(i, w * pi)
                if tr is None:
                    continue
                verts, parent, delay = tr
                rc = delay + pi[list(verts)].sum() - mu[i]
                best_rc = min(best_rc, rc)
                if rc < -1e-6 and (i, verts) not in seen:
                    seen.add((i, verts))
                    cols.append(dict(net=i, verts=verts, parent=parent, delay=delay, source="cg"))
                    added += 1
        print(f"  round {rnd}: LP {lp.fun:.1f}, columns {len(cols)}, added {added}, most negative "
              f"reduced cost {best_rc:.1f}, {time.time() - t0:.0f}s", flush=True)
        if added == 0:
            break

A, A_one, c = matrices()
used = np.flatnonzero(A.getnnz(axis=1) > 1)
cons = [LinearConstraint(A_one, 1, 1), LinearConstraint(A[used], 0, 1)]
per_net = pd.Series([col["net"] for col in cols]).value_counts()
print(f"columns {len(cols)}, per net median {per_net.median():.0f}, max {per_net.max()}")
lp = milp(c, constraints=cons, integrality=np.zeros(len(cols)), bounds=(0, 1))
print(f"LP relaxation over the pool: {lp.fun:.1f}")
res = milp(c, constraints=cons, integrality=np.ones(len(cols)), bounds=(0, 1),
           options={"time_limit": args.mip_seconds})
if res.x is None:
    sys.exit(f"MIP found no solution: {res.message}")
pick = np.flatnonzero(res.x > 0.5)
src = pd.Series([cols[j]["source"] for j in pick]).value_counts().to_dict()
total = sum(cols[j]["delay"] for j in pick)
print(f"MIP {res.message}: total {total:.0f} vs given {given_total:.0f} "
      f"({100 * (total / given_total - 1):+.2f}%), picked {src}")
routes = [{"net": nets[cols[j]["net"]]["id"],
           "edges": [[xyz(p), xyz(v)] for v, p in cols[j]["parent"].items() if p != -1]}
          for j in pick]
json.dump({"format": "m3d-submission", "version": 1, "instance": inst["name"], "routes": routes},
          open(args.out, "w"))
print("wrote", args.out, "- verify with: python3 -m m3d.cli evaluate --case",
      f"{suite}/{args.case}.json --sol {args.out} --suite {suite}")
